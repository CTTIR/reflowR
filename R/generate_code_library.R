# ── Calibration Plot ──
wf_calibration_plot <- function(predicted, observed, n_bins = 10, title = NULL) {{

  df <- tibble::tibble(predicted = predicted, observed = observed) |>
    dplyr::mutate(bin = cut(predicted, breaks = n_bins, include.lowest = TRUE)) |>
    dplyr::group_by(bin) |>
    dplyr::summarise(
      mean_pred = mean(predicted),
      mean_obs  = mean(observed),
      n = dplyr::n(),
      .groups = "drop"
    )

  ggplot2::ggplot(df, ggplot2::aes(x = mean_pred, y = mean_obs)) +
    ggplot2::geom_abline(slope = 1, intercept = 0, linetype = "dashed",
                         color = wf_colors$grey) +
    ggplot2::geom_point(size = 3, color = wf_colors$primary) +
    ggplot2::geom_line(color = wf_colors$primary_light, linewidth = 0.8) +
    theme_wf() +
    ggplot2::labs(x = "Predicted", y = "Observed", title = title) +
    ggplot2::coord_equal()
}}

