    gtsummary::bold_labels()

  if (!is.null(strata)) {{
    tbl <- tbl |> gtsummary::add_p() |> gtsummary::add_overall()
  }}

  tbl
}}

# ── Correlation Pipeline ──
wf_cor_analysis <- function(df, vars = NULL, method = "pearson",
                            threshold = 0.7, save_plot = TRUE) {{

  if (is.null(vars)) vars <- names(df)[sapply(df, is.numeric)]
  mat <- cor(df[, vars, drop = FALSE], use = "pairwise.complete.obs", method = method)

  # Find high correlations
  high_cors <- which(abs(mat) >= threshold & upper.tri(mat), arr.ind = TRUE)
  high_df <- if (nrow(high_cors) > 0) {{
    tibble::tibble(
      var1 = rownames(mat)[high_cors[, 1]],
      var2 = colnames(mat)[high_cors[, 2]],
      cor  = mat[high_cors]
    ) |> dplyr::arrange(dplyr::desc(abs(cor)))
  }} else {{
    tibble::tibble(var1 = character(), var2 = character(), cor = numeric())
  }}

  plot <- wf_cor_heatmap(df, vars = vars, method = method)
  if (save_plot) save_wf_plot(plot, "correlation_heatmap")

  list(matrix = mat, high_cors = high_df, plot = plot)
}}

# ── Missing Data Assessment ──
wf_missing_assessment <- function(df, pattern_plot = TRUE) {{

  summary_tbl <- missing_summary(df)
  pct_complete <- round(mean(stats::complete.cases(df)) * 100, 1)

  plots <- list()
  if (requireNamespace("naniar", quietly = TRUE)) {{
    plots$vis_miss <- naniar::vis_miss(df) + theme_wf()
    if (pattern_plot && ncol(df) <= 30 && sum(colSums(is.na(df)) > 0) >= 2) {{
      plots$upset <- tryCatch(naniar::gg_miss_upset(df), error = function(e) NULL)
    }}
  }}

  list(summary_table = summary_tbl, pct_complete = pct_complete, plots = plots)
}}

# ── Outlier Detection ──
wf_detect_outliers <- function(df, vars = NULL, method = c("iqr", "zscore"),
                               threshold = 1.5) {{
  method <- match.arg(method)
  if (is.null(vars)) vars <- names(df)[sapply(df, is.numeric)]

  purrr::map_dfr(vars, function(v) {{
    x <- df[[v]]
    if (method == "iqr") {{
      q <- quantile(x, c(0.25, 0.75), na.rm = TRUE)
      iqr <- q[2] - q[1]
      lower <- q[1] - threshold * iqr
      upper <- q[2] + threshold * iqr
    }} else {{
      mu <- mean(x, na.rm = TRUE)
      s  <- sd(x, na.rm = TRUE)
      lower <- mu - threshold * s
      upper <- mu + threshold * s
    }}
    tibble::tibble(
      variable    = v,
      row_id      = seq_along(x),
      value       = x,
      lower_bound = lower,
      upper_bound = upper,
      is_outlier  = !is.na(x) & (x < lower | x > upper)
    ) |> dplyr::filter(is_outlier)
  }})
}}

# ── Model Comparison Helper ──
wf_compare_models <- function(..., metrics = c("accuracy", "roc_auc")) {{
  results <- list(...)
  names(results) <- paste0("Model_", seq_along(results))
  if (!is.null(names(list(...)))) {{
    nn <- names(list(...))
    names(results)[nn != ""] <- nn[nn != ""]
  }}

  purrr::map_dfr(names(results), function(nm) {{
    res <- results[[nm]]
    if (inherits(res, "tune_results")) {{
      tune::collect_metrics(res) |>
        dplyr::filter(.metric %in% metrics) |>
        dplyr::mutate(model = nm)
    }} else {{
      tibble::tibble(model = nm, .metric = "custom", mean = NA_real_)
    }}
  }})
}}

# ── Checkpoint Loader ──
wf_load_checkpoint <- function(step_name, dir = paths$processed) {{
  pattern <- paste0("^", step_name, "_\\\\d{{8}}_\\\\d{{6}}\\\\.rds$")
  files <- list.files(dir, pattern = pattern, full.names = TRUE)
  if (length(files) == 0) {{
    cli::cli_abort("No checkpoint found for {{.val {{step_name}}}} in {{.path {{dir}}}}")
  }}
  latest <- files[which.max(file.info(files)$mtime)]
  cli::cli_alert_info("Loading checkpoint: {{.path {{basename(latest)}}}}")
  readRDS(latest)
}}
')
}


