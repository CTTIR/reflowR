# ── Inline Results Formatter ──
wf_inline <- function(x, digits = 2, type = c("number", "p", "ci"),
                      prefix = "", suffix = "") {{
  type <- match.arg(type)
  result <- switch(type,
    number = sprintf(paste0("%.", digits, "f"), x[1]),
    p = {{
      if (x[1] < 0.001) "< 0.001"
      else if (x[1] < 0.01) sprintf("%.3f", x[1])
      else sprintf(paste0("%.", digits, "f"), x[1])
    }},
    ci = {{
      if (length(x) >= 2) {{
        sprintf(paste0("%.", digits, "f (95%% CI: %.", digits, "f, %.", digits, "f)"),
                x[1], x[1], x[2])
      }} else sprintf(paste0("%.", digits, "f"), x[1])
    }}
  )
  paste0(prefix, result, suffix)
}}

# ── Frequency Cross-Table ──
wf_crosstab <- function(df, row_var, col_var, margins = TRUE, test = TRUE) {{
  tbl <- df |>
    dplyr::count(.data[[row_var]], .data[[col_var]]) |>
    tidyr::pivot_wider(names_from = dplyr::all_of(col_var), values_from = n, values_fill = 0)

  gt_tbl <- gt::gt(tbl, rowname_col = row_var) |> gt_wf_style()

  if (test) {{
    ct <- stats::chisq.test(table(df[[row_var]], df[[col_var]]))
    gt_tbl <- gt_tbl |>
      gt::tab_footnote(sprintf("Chi-squared = %.2f, df = %d, p = %s",
                               ct$statistic, ct$parameter, fmt_pval(ct$p.value)))
  }}

  gt_tbl
}}
')
}


