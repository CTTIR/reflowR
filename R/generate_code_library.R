#' Generate the Code Library Files
#'
#' Creates `code/formulary.R`, `code/data_io.R`, `code/table_helpers.R`,
#' and `code/plot_helpers.R` in the project directory.
#'
#' @param project_dir Character. Path to the project root.
#' @param scheme A scheme list from [reflow_scheme()].
#' @param preset A preset list from [reflow_preset()].
#'
#' @return Invisibly returns a character vector of created file paths.
#'
#' @keywords internal
generate_code_library <- function(project_dir, scheme, preset) {
  code_dir <- fs::path(project_dir, "code")
  files <- character(4)

  # ── formulary.R ──
  files[1] <- fs::path(code_dir, "formulary.R")
  writeLines(generate_formulary_content(scheme), files[1])

  # ── data_io.R ──
  files[2] <- fs::path(code_dir, "data_io.R")
  writeLines(generate_data_io_content(scheme), files[2])

  # ── table_helpers.R ──
  files[3] <- fs::path(code_dir, "table_helpers.R")
  writeLines(generate_table_helpers_content(scheme), files[3])

  # ── plot_helpers.R ──
  files[4] <- fs::path(code_dir, "plot_helpers.R")
  writeLines(generate_plot_helpers_content(scheme), files[4])

  invisible(files)
}

