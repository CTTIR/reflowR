# ── Volcano Plot ──
wf_volcano_plot <- function(results, fc_col = "log2fc", p_col = "p_value",
                            fc_threshold = 1, p_threshold = 0.05,
                            label_col = NULL, title = NULL) {{

  df <- results |>
    dplyr::mutate(
      neg_log_p = -log10(.data[[p_col]]),
      significance = dplyr::case_when(
        abs(.data[[fc_col]]) >= fc_threshold & .data[[p_col]] < p_threshold ~ "Significant",
        TRUE ~ "NS"
      )
    )

  p <- ggplot2::ggplot(df, ggplot2::aes(x = .data[[fc_col]], y = neg_log_p,
                                        color = significance)) +
    ggplot2::geom_point(alpha = 0.6, size = 1.5) +
    ggplot2::scale_color_manual(values = c("Significant" = wf_colors$accent,
                                           "NS" = wf_colors$grey)) +
    ggplot2::geom_hline(yintercept = -log10(p_threshold), linetype = "dashed",
                        color = wf_colors$grey) +
    ggplot2::geom_vline(xintercept = c(-fc_threshold, fc_threshold),
                        linetype = "dashed", color = wf_colors$grey) +
    theme_wf() +
    ggplot2::labs(x = "Log2 Fold Change", y = "-Log10 P-value", title = title)

  if (!is.null(label_col)) {{
    sig_df <- dplyr::filter(df, significance == "Significant")
    p <- p + ggrepel::geom_text_repel(
      data = sig_df,
      ggplot2::aes(label = .data[[label_col]]),
      size = 3, max.overlaps = 20
    )
  }}

  p
}}

