# ── Universal Data Reader ──
wf_read_data <- function(file, sheet = 1, skip = 0,
                         na_strings = c("", "NA", "N/A", ".")) {{

  ext <- tolower(tools::file_ext(file))
  df <- switch(ext,
    csv  = readr::read_csv(file, skip = skip, na = na_strings, show_col_types = FALSE),
    tsv  = readr::read_tsv(file, skip = skip, na = na_strings, show_col_types = FALSE),
    xlsx = readxl::read_excel(file, sheet = sheet, skip = skip, na = na_strings),
    xls  = readxl::read_excel(file, sheet = sheet, skip = skip, na = na_strings),
    sav  = haven::read_sav(file),
    dta  = haven::read_dta(file),
    rds  = readRDS(file),
    rda  = {{ e <- new.env(); load(file, envir = e); as.list(e)[[1]] }},
    {{ cli::cli_abort("Unsupported file format: {{.val {{ext}}}}") }}
  )

  df <- janitor::clean_names(df)
  cli::cli_alert_success("Read {{.path {{basename(file)}}}}: {{nrow(df)}} rows x {{ncol(df)}} cols")
  tibble::as_tibble(df)
}}

# ── Batch Reader ──
wf_read_all <- function(dir = paths$raw, pattern = NULL, recursive = FALSE) {{
  exts <- c("csv", "tsv", "xlsx", "xls", "sav", "dta", "rds")
  if (is.null(pattern)) pattern <- paste0("\\\\.(", paste(exts, collapse = "|"), ")$")
  files <- list.files(dir, pattern = pattern, full.names = TRUE, recursive = recursive)
  if (length(files) == 0) {{
    cli::cli_warn("No data files found in {{.path {{dir}}}}")
    return(list())
  }}
  result <- purrr::map(files, wf_read_data)
  names(result) <- tools::file_path_sans_ext(basename(files))
  cli::cli_alert_success("Read {{length(result)}} file(s) from {{.path {{dir}}}}")
  result
}}

# ── Standardized Export ──
wf_export <- function(obj, filename, dir = NULL, formats = c("rds"),
                      versioned = FALSE) {{

  if (versioned) {{
    filename <- paste0(filename, "_", format(Sys.time(), "%Y%m%d_%H%M%S"))
  }}

  if (inherits(obj, "data.frame")) {{
    if (is.null(dir)) dir <- paths$processed
    for (fmt in formats) {{
      out <- file.path(dir, paste0(filename, ".", fmt))
      switch(fmt,
        rds  = saveRDS(obj, out),
        csv  = readr::write_csv(obj, out),
        xlsx = writexl::write_xlsx(obj, out),
        sav  = haven::write_sav(obj, out),
        cli::cli_warn("Unknown format: {{.val {{fmt}}}}")
      )
    }}
  }} else if (inherits(obj, "gg") || inherits(obj, "ggplot")) {{
    if (is.null(dir)) dir <- paths$figures
    save_wf_plot(obj, filename, dir = dir)
  }} else if (inherits(obj, c("gt_tbl", "gtsummary"))) {{
    if (is.null(dir)) dir <- paths$tables
    for (fmt in formats) {{
      out <- file.path(dir, paste0(filename, ".", fmt))
      switch(fmt,
        html = {{ gt_obj <- if (inherits(obj, "gtsummary")) gtsummary::as_gt(obj) else obj
                  gt::gtsave(gt_obj, out) }},
        docx = {{ ft <- if (inherits(obj, "gtsummary")) gtsummary::as_flex_table(obj)
                       else flextable::as_flextable(obj)
                  flextable::save_as_docx(ft, path = out) }},
        cli::cli_warn("Unknown format for table: {{.val {{fmt}}}}")
      )
    }}
  }} else {{
    if (is.null(dir)) dir <- paths$processed
    saveRDS(obj, file.path(dir, paste0(filename, ".rds")))
  }}

  cli::cli_alert_success("Exported: {{.val {{filename}}}}")
  invisible(filename)
}}

# ── Data Dictionary Generator ──
wf_data_dict <- function(df, output_file = NULL) {{

  dict <- purrr::map_dfr(names(df), function(v) {{
    x <- df[[v]]
    tibble::tibble(
      variable       = v,
      type           = class(x)[1],
      n_unique       = length(unique(x[!is.na(x)])),
      n_missing      = sum(is.na(x)),
      pct_missing    = round(mean(is.na(x)) * 100, 1),
      min            = if (is.numeric(x)) as.character(round(min(x, na.rm = TRUE), 4)) else NA_character_,
      max            = if (is.numeric(x)) as.character(round(max(x, na.rm = TRUE), 4)) else NA_character_,
      example_values = paste(utils::head(unique(x[!is.na(x)]), 3), collapse = ", ")
    )
  }})

  if (!is.null(output_file)) {{
    writexl::write_xlsx(dict, output_file)
    cli::cli_alert_success("Data dictionary saved: {{.path {{output_file}}}}")
  }}

  dict
}}

# ── Label Extractor (SPSS / REDCap) ──
wf_extract_labels <- function(df) {{
  purrr::map_dfr(names(df), function(v) {{
    x <- df[[v]]
    var_label <- attr(x, "label") %||% NA_character_
    val_labels <- attr(x, "labels")
    val_str <- if (!is.null(val_labels)) {{
      paste(paste0(val_labels, " = ", names(val_labels)), collapse = "; ")
    }} else NA_character_
    tibble::tibble(variable = v, label = var_label, value_labels = val_str)
  }})
}}
')
}


