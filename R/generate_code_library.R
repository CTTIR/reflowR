# ── Normality Assessment ──
wf_normality_battery <- function(df, vars = NULL, alpha = 0.05) {{

  if (is.null(vars)) vars <- names(df)[sapply(df, is.numeric)]

  results <- purrr::map_dfr(vars, function(v) {{
    x <- df[[v]][!is.na(df[[v]])]
    if (length(x) < 3 || length(x) > 5000) {{
      return(tibble::tibble(variable = v, statistic = NA_real_,
                            p_value = NA_real_, normal = NA))
    }}
    test <- stats::shapiro.test(x)
    tibble::tibble(
      variable  = v,
      statistic = test$statistic,
      p_value   = test$p.value,
      normal    = test$p.value >= alpha
    )
  }})

  results
}}

# ── Group Comparison Selector ──
wf_compare_groups <- function(df, outcome, group, paired = FALSE) {{

  g <- df[[group]]
  y <- df[[outcome]]
  n_groups <- length(unique(g[!is.na(g)]))

  # Test normality per group
  norm_ok <- all(
    tapply(y, g, function(x) {{
      x <- x[!is.na(x)]
      if (length(x) < 3 || length(x) > 5000) return(TRUE)
      stats::shapiro.test(x)$p.value >= 0.05
    }})
  )

  if (n_groups == 2) {{
    if (norm_ok) {{
      test <- if (paired) stats::t.test(y ~ g, paired = TRUE) else stats::t.test(y ~ g)
      test_name <- ifelse(paired, "Paired t-test", "Welch t-test")
    }} else {{
      test <- if (paired) stats::wilcox.test(y ~ g, paired = TRUE) else stats::wilcox.test(y ~ g)
      test_name <- ifelse(paired, "Wilcoxon signed-rank", "Wilcoxon rank-sum")
    }}
    es <- effectsize::effectsize(test)
  }} else {{
    if (norm_ok) {{
      test <- stats::aov(as.formula(paste(outcome, "~", group)), data = df)
      test_name <- "One-way ANOVA"
      es <- effectsize::eta_squared(test)
    }} else {{
      test <- stats::kruskal.test(as.formula(paste(outcome, "~", group)), data = df)
      test_name <- "Kruskal-Wallis"
      es <- effectsize::rank_epsilon_squared(
        as.formula(paste(outcome, "~", group)), data = df
      )
    }}
  }}

  list(test_name = test_name, test = test, effect_size = es)
}}

