test_that("file hashes are SHA-256 of the file bytes", {
  dir <- withr::local_tempdir()
  file <- file.path(dir, "a.txt")
  writeLines("alpha", file)
  expect_identical(rf_file_hashes(file), digest::digest(file = file, algo = "sha256"))
  expect_identical(rf_file_hash(file), rf_file_hashes(file))
  expect_identical(rf_file_hashes(character()), character())
  expect_error(rf_file_hashes(file.path(dir, "missing")), "Cannot read")
})

test_that("the package hash cache is opt-in and follows file changes", {
  dir <- withr::local_tempdir()
  files <- file.path(dir, c("a.txt", "b.txt"))
  writeLines("alpha", files[1])
  writeLines("beta", files[2])
  plain <- rf_file_hashes(files)
  withr::local_options(reflowR.package_hash_cache = FALSE)
  expect_identical(rf_package_hashes(files), plain)
  writeLines("gamma", files[2])
  expect_identical(rf_package_hashes(files), rf_file_hashes(files))
  writeLines("beta", files[2])

  withr::local_options(reflowR.package_hash_cache = TRUE)
  expect_identical(rf_package_hashes(files), plain)
  expect_identical(rf_package_hashes(rev(files)), rev(plain))
  writeLines("changed", files[1])
  expect_identical(rf_package_hashes(files), rf_file_hashes(files))
  expect_false(identical(rf_package_hashes(files)[1], plain[1]))
  # Same size and restored modification time: the change time still differs.
  before <- file.mtime(files[1])
  writeLines("CHANGED", files[1])
  Sys.setFileTime(files[1], before)
  expect_identical(rf_package_hashes(files), rf_file_hashes(files))
  expect_error(rf_package_hashes(file.path(dir, "missing")), "Cannot read")
})

test_that("the input hash cache is opt-in, separate and follows file changes", {
  dir <- withr::local_tempdir()
  file <- file.path(dir, "input.txt")
  writeLines("one", file)
  first <- rf_file_hashes(file)
  withr::local_options(reflowR.input_hash_cache = FALSE, reflowR.package_hash_cache = FALSE)
  expect_identical(rf_input_hashes(file), first)
  withr::local_options(reflowR.input_hash_cache = TRUE)
  expect_identical(unname(rf_tree(file)), first)
  writeLines("two", file)
  expect_identical(unname(rf_tree(file)), rf_file_hashes(file))
  expect_false(identical(rf_input_hashes(file), first))
})

test_that("tree walks refuse links below the root", {
  skip_on_os("windows")
  # Resolved, because the temporary folder can lie below a link (/var on macOS).
  dir <- normalizePath(withr::local_tempdir())
  dir.create(file.path(dir, "sub"))
  writeLines("x", file.path(dir, "sub", "a.txt"))
  expect_identical(rfa_tree(dir)$files, "sub/a.txt")
  file.symlink(file.path(dir, "sub", "a.txt"), file.path(dir, "sub", "link.txt"))
  expect_error(rfa_tree(dir), "Symbolic links")
})
